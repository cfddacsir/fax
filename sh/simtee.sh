##===[ Functions ==========================================
fnow () { 
    now=(`date +%Y%m%d-%H%M%S`); printf $now;
};
loo () { 
    loo=$(ls -tr *log*|ta1) ;
};
pfs () { 
     OUT=$(printf "%${2}s"|sed "s/ /${1}/g"); printf '%s' $OUT;
};
pbr () { 
           printf "%s \n" $(pfs '=' 60); };
ADIV=$(pfs '-' 60);
BDIV=$(pfs '=' 60);
status(){
		pbr  
		date 
		ls -latr $PWD/ 
		pbr 
};

##=========================================================
summary(){
o="
# alias starccm  `alias starccm `
# alias starccm+ `alias starccm+`
# PATH:        ${PATH} 
"
PNOW=$(fnow);
printf "\n $BDIV \n
STAR
  STARVERS    ${STARVERS} 
  starccm     `which starccm `
  starccm+    `which starccm+`
  TIME:     	$PNOW
  RUNDIR:   	$RUNDIR
  SIMFILE:		$SIMFILE
  SIMCASE:  	$SIMCASE
  LOGFILE:  	$loo

 OPTIONS:     $OPTIONS
  * lic:      $OPT_LIC :( license ): 
  * NP:        $NP  \\ :(number of processor cores ):\\
  * OPERA:     $OPERA \\ :(run, mesh, gui, java :\\
  * OPT_MPI:   $OPT_MPI  \\ \t\t:(-mpi openmpi) \\
  * OPT_GRAPH: $OPT_GRAPH \\ \t\t:(-graphics ): \\
* ----------------------------------------------------------
>> Executing: $doing \n $BDIV \n" ;
	}

