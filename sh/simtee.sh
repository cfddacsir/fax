###-----------------------------------------------------------------------------
middle(){
  if [[ "${OPERA}" == "mesh" ]] ; then 
    memorywatch.sh i 4 s 15 &
  fi
#   /opt/Siemens/${STARVERS}/STAR-CCM+${STARVERS}/star/bin/starccm+ \
#      ${OPT_LIC} ${OPT_MPI} -np ${NP} -batch ${OPERA} ${SIMFILE} | tee -a ${loo} 
   exec ${doing}  | tee -a $loo ;

}

###-----------------------------------------------------------------------------

end(){
  touch ./STOP ;
  touch ./END_$ew ;

  status  | tee -a $loo ;
  tail -n 20 $loo ;

  if [[ "${OPERA}" == "mesh" ]] ; then 
    #if [[ -f ./memorysum.txt ]] ; then 
    /home/common/sh/gen_memusage.sh &
  fi
  if [[ "${OPERA}" == "run" ]] ; then 
	  mkdir -pv  rep/loo/ ;
	  /home/common/lib/qstar.py ; ### exec:python3 qstar ;
    cp -vfp --preserve=timestamps $loo.stat.txt  ${SIMCASE}.runstat.txt_$(fnow) ;
    cp -vfp --preserve=timestamps *runstat* *run.log* rep/loo/ ;
    mv -v *.png rep/ ;

  fi;
  status  | tee -a $loo ;
  PNOW=$(fnow) ;
  cp -pvf $loo ${SIMCASE}.${OPERA}.log_$(fnow) ;

  . /home/common/sh/calc_stardur.sh ${OPERA} ;

} 
###-----------------------------------------------------------------------------


exes() { #~~~
  ( bootup ) ;
  printf " STARVERS : ${STARVERS} \n" ;
  touch ./BEG_$ew ;

  RUNDIR=$( pwd );
  SIMFILE=$(ls -tr *.sim | grep -v sim~ | tail -n1 ) ;
  SIMCASE=$(basename -a ${SIMFILE%%.sim} ) ;
  loo=${RUNDIR}/${SIMCASE}_${OPERA}.log ;

  printf " RUNDIR : ${RUNDIR}  \n" ;
  printf " SIMFILE: ${SIMFILE} \n" ;
  printf " SIMCASE: ${SIMCASE} \n" ;
  printf " loo    : ${loo}     \n" ;

  if [ $(ls -tr ${loo} | tail -n1) ]; then
       cp -vf --preserve=timestamps ${loo} ${loo}__$( 
		   printf $(ls -la --time-style='+%Y%m%d-%H%M' ${loo} |awk '{print $6}')) ;
  fi;

  OPTIONS="$OPT_LIC $OPT_NP $OPT_MPI $OPT_GRAPH $OPERA ";

# doing="/opt/Siemens/${STARVERS}/STAR-CCM+${STARVERS}/star/bin/starccm+ -power ${OPT_MPI} -np ${NP} -batch ${OPERA} ${SIMFILE} | tee -a ${loo} " ;

  doing="starccm+ -power ${OPT_MPI} -np ${NP} -batch ${OPERA} ${SIMFILE} | tee -a ${loo} " ;
  doing="starccm+ -power ${OPT_MPI} -np ${NP} -batch ${OPERA} ${SIMFILE} " ;

  summary  | tee -a $loo
# status   | tee -a $loo

  ( middle ) ;
  ( end )    ;

}


